    "```",
    "",
    "## 12. Формула проекта",
    "",
    "```",
    "G(t+1) = Рост(G(t), μ*, D*)  при s* = argmax f(s)",
    "```",
    "",
    "где:",
    "- G(t) — топология сети в момент t",
    "- μ* — оптимальное ветвление",
    "- D* — оптимальная диффузия",
