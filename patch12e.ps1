$math = @(
    "# InevioNet — Формальная математика",
    "",
    "## 1. Ложный выбор → Мицелий",
    "",
    "**Психология:** «пиво, вино или водка» — иллюзия выбора.",
    "",
    "**Формализация:**",
    "```",
    "A = {a_1, ..., a_n}  — множество альтернатив",
    "f: A → R             — функция исходов",
    "f(a_i) = r           — все ведут к одному",
    "```",
    "",
    "**Ложный выбор:** `|A| > 1` и `|f(A)| = 1`",
    "",
    "**Мицелий:** растёт **во все стороны** → `|f(A)| ≫ 1`",
    "",
    "## 2. Геном как вектор",
    "",
    "```",
    "g = (g_1, ..., g_n) ∈ [0,1]^5 × Z^4 × E^k",
    "```",
    "",
    "где:",
    "- 5 float генов (speed, reliability, stealth, efficiency, adaptability)",
    "- 4 int гена (packet_size, ttl, priority, clone_threshold)",
    "- k enum генов (penetration, masking, industrial, stego)",
    "",
    "## 3. Fitness функция",
    "",
    "```",
    "f(g) = Σ_i w_i · g_i + bonus(g)",
    "```",
    "",
    "где `w = (0.25, 0.30, 0.20, 0.15, 0.10)`",
    "",
    "**Bonus:**",
    "```",
    "size_bonus = max(0, 1 - |packet_size - 1400|/1400) · 0.05",
    "ttl_bonus = min(1, ttl/40) · 0.03",
    "priority_bonus = max(0, 1 - |priority-7|/10) · 0.02",
    "```",
    "",
    "## 4. Эволюция",
    "",
    "**Турнирный отбор:**",
    "```",
    "P_select(g_i) = P(g_i ∈ tournament_size)",
    "winner = argmax_{g ∈ T} f(g)",
    "```",
    "",
    "**Мутация:**",
    "```",
    "g'_i = g_i + N(0, σ²)  с вероятностью p_m",
    "```",
    "",
    "**Кроссовер:**",
    "```",
    "child_i = α·parent1_i + (1-α)·parent2_i + N(0, 0.05)",
    "```",
    "",
    "## 5. Diversity (разнообразие)",
    "",
    "```",
    "D = (1/n) Σ_i σ_i",
    "```",
    "",
    "где σ_i — стандартное отклонение гена i по популяции.",
    "",
    "**Проблема:** D → 0 при сходимости (преждевременная конвергенция).",
    "",
    "**Решение:** КАТАСТРОФА каждые 50 поколений:",
    "```",
    "1. Оставить 70% лучших",
    "2. Инжектировать 30% случайных геномов",
    "3. D растёт обратно",
    "```",
    "",
    "## 6. Reward",
    "",
    "```",
    "f(g, strategy) += +0.1  если success",
    "f(g, strategy) += -0.05 если failure",
    "```",
    "",
    "где `strategy = getattr(g, attr)` для `attr ∈ {penetration, masking, stego, industrial}`",
    "",
    "## 7. Мицелий",
    "",
    "**Апикальный рост:**",
    "```",
    "x_{t+1} = x_t + Δ · (cos θ_t, sin θ_t)",
    "θ_{t+1} = θ_t + N(0, σ²)",
    "```",
    "",
    "**Ветвление:** процесс Гальтона-Ватсона:",
    "```",
    "E[N(t)] = N_0 · μ^t",
    "```",
    "",
    "**Анастомозы:** цикломатическая сложность:",
    "```",
    "C = E - V + 1",
    "```",
    "",
    "## 8. Феромоны",
    "",
    "**Испарение:**",
    "```",
    "s(t) = s_0 · exp(-λ · t / 60)",
    "```",
    "",
    "**Усиление:**",
    "```",
    "s ← min(1, s + 0.1)",
    "```",
    "",
    "**Оценка:**",
    "```",
    "score = strength · success_rate",
    "```",
    "",
    "## 9. Споры",
    "",
    "**Жизнеспособность:**",
    "```",
    "v(t) = v_0 - 0.05 · t",
    "```",
    "",
    "**Условие выживания:**",
    "```",
    "N_s · p > 1",
    "```",
    "",
    "где N_s — число спор, p — вероятность прорастания.",
    "",
    "## 10. Маскировка",
    "",
    "**KL-дивергенция:**",
    "```",
    "D_KL(P || Q) = Σ P(i) · log(P(i) / Q(i))",
    "```",
    "",
    "**Байесовский выбор:**",
    "```",
    "P(channel) = α / (α + β)",
    "```",
    "",
    "где α, β — параметры Beta-распределения.",
    "",
    "## 11. P2P Bridge",
    "",
    "**Broker:**",
    "```",
    "relay* = argmin_{r ∈ Relays} load_ratio(r)",
    "load_ratio(r) = current_load(r) / capacity(r)",
    "```",
    "",
    "**WebRTC:**",
    "```",
    "Offer: SDP_A → Broker → SDP_B (Answer)",
